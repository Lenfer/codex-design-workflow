#!/usr/bin/env python3
"""Install the Design router and pinned sources without changing Codex configuration."""
import argparse
import contextlib
import importlib.util
import io
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parent
SOURCE_SKILL = ROOT / 'skills' / 'design'
spec = importlib.util.spec_from_file_location('design_library', SOURCE_SKILL / 'scripts/library.py')
lib = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lib)


def safe_rel(value):
    path = PurePosixPath(value)
    if not value or path.is_absolute() or '..' in path.parts or '\\' in value:
        raise ValueError('Invalid relative source path')
    return Path(*path.parts)


def validate(entries):
    for key, entry in entries.items():
        if not re.fullmatch(r'[a-z][a-z0-9-]*', key):
            raise ValueError('Invalid source ID')
        if not re.fullmatch(r'https://github.com/[\w.-]+/[\w.-]+\.git', entry['source']):
            raise ValueError('Only pinned public GitHub sources are supported')
        if not re.fullmatch(r'[0-9a-f]{40}', entry['commit']):
            raise ValueError('A full commit hash is required')
        if not re.fullmatch(r'[0-9a-f]{64}', entry['tree_sha256']):
            raise ValueError('A SHA-256 content hash is required')
        for name in ['paths', 'entrypoints', 'license_paths']:
            if not entry[name]:
                raise ValueError('Missing paths: ' + name)
            for path in entry[name]:
                safe_rel(path)


def git(*args, cwd):
    env = dict(os.environ, GIT_TERMINAL_PROMPT='0')
    return subprocess.run(['git', '-c', 'core.hooksPath=/dev/null',
                           '-c', 'protocol.file.allow=never', *args], cwd=cwd,
                          env=env, capture_output=True, check=True, timeout=180).stdout


def download(entry, dest):
    with tempfile.TemporaryDirectory(prefix='design-source-') as tmp:
        git('init', '-q', cwd=tmp)
        git('remote', 'add', 'origin', entry['source'], cwd=tmp)
        git('fetch', '--depth=1', 'origin', entry['commit'], cwd=tmp)
        actual = git('rev-parse', 'FETCH_HEAD', cwd=tmp).decode().strip()
        if actual != entry['commit']:
            raise ValueError('Fetched commit differs from lock file')
        archive = git('archive', entry['commit'], '--', *entry['paths'], cwd=tmp)
        dest.mkdir(parents=True)
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            for member in tar:
                path = dest / safe_rel(member.name)
                if member.isdir():
                    path.mkdir(parents=True, exist_ok=True)
                elif member.isfile():
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(tar.extractfile(member).read())
                    path.chmod(0o755 if member.mode & 0o111 else 0o644)
                else:
                    raise ValueError('Unsupported archive member: ' + member.name)


def clean_copy(src, dest):
    # Never copy Python caches generated by installer imports or tests.
    shutil.copytree(src, dest, symlinks=True,
                    ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))


def same(left, right):
    return left.is_dir() and lib.digest(left) == lib.digest(right)


@contextlib.contextmanager
def install_lock(target):
    lock = target / '.design-workflow-install.lock'
    try:
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError:
        raise ValueError('Another install or stale lock exists: ' + str(lock))
    os.close(fd)
    try:
        yield
    finally:
        lock.unlink()


def reject_symlink_parents(path):
    for parent in [path, *path.parents]:
        if parent.is_symlink():
            raise ValueError('Install paths must not traverse symlinks: ' + str(parent))


def install(target, entries, source_cache=None):
    target = target.resolve()
    skill = target / '.agents/skills/design'
    library = target / '.design-workflow/library'
    reject_symlink_parents(skill)
    reject_symlink_parents(library)
    target.mkdir(parents=True, exist_ok=True)
    with install_lock(target), tempfile.TemporaryDirectory(prefix='design-install-') as tmp:
        stage = Path(tmp)
        staged_skill = stage / 'design'
        clean_copy(SOURCE_SKILL, staged_skill)
        (staged_skill / 'installation.json').write_text(json.dumps({
            'library': os.path.relpath(library, skill)
        }, indent=2) + '\n')
        if skill.exists() and not same(skill, staged_skill):
            raise ValueError('Existing Design skill differs; preserved: ' + str(skill))
        pending = []
        # Complete all downloads and checks before exposing a new router.
        for key, entry in entries.items():
            dest = library / key / entry['commit']
            reject_symlink_parents(dest)
            if dest.exists():
                lib.verify(dest, entry)
                continue
            staged = stage / 'library' / key / entry['commit']
            if source_cache:
                src = source_cache / key / entry['commit']
                lib.verify(src, entry)
                clean_copy(src, staged)
            else:
                print('Fetching ' + key + '@' + entry['commit'][:12], flush=True)
                download(entry, staged)
            lib.verify(staged, entry)
            pending.append((staged, dest))
        for src, dest in pending:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(src, dest)
        if not skill.exists():
            skill.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(staged_skill, skill)
    return skill


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['plan', 'install', 'doctor'])
    scope = parser.add_mutually_exclusive_group(required=True)
    scope.add_argument('--target', type=Path, help='Project directory (recommended)')
    scope.add_argument('--user', action='store_true', help='Install into your home directory')
    parser.add_argument('--source-cache', type=Path,
                        help='Offline releases/<id>/<commit> cache; hashes still checked')
    args = parser.parse_args()
    target = (Path.home() if args.user else args.target).resolve()
    entries = lib.catalog()
    validate(entries)
    if args.action == 'plan':
        print(json.dumps({'target': str(target), 'skill': str(target / '.agents/skills/design'),
                          'library': str(target / '.design-workflow/library'),
                          'sources': {k: e['commit'] for k, e in entries.items()},
                          'codex_config_changes': False, 'app_installs': False}, indent=2))
    elif args.action == 'install':
        skill = install(target, entries, args.source_cache)
        print('Installed: ' + str(skill))
        print('Next: run doctor, then follow docs/SETUP.md for live MCP checks.')
    else:
        skill = target / '.agents/skills/design'
        reject_symlink_parents(skill)
        for key, entry in entries.items():
            lib.verify(target / '.design-workflow/library' / key / entry['commit'], entry)
        with tempfile.TemporaryDirectory() as tmp:
            expected = Path(tmp) / 'design'
            clean_copy(SOURCE_SKILL, expected)
            (expected / 'installation.json').write_text(json.dumps({
                'library': os.path.relpath(target / '.design-workflow/library', skill)
            }, indent=2) + '\n')
            if not same(skill, expected):
                raise ValueError('Installed router differs from this checkout')
        print('PASS: router and all seven pinned sources verified.')
        print('MCP connectivity: NOT TESTED by filesystem doctor; use docs/SETUP.md.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, subprocess.SubprocessError) as exc:
        # Do not dump arbitrary Git stderr or environment values into logs.
        print('Installation stopped: ' + str(exc), file=sys.stderr)
        sys.exit(1)
